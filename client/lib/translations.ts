export function getTranslation(language: Language, key: string): string {
  const keys = key.split(".");
  let value: any = translations[language];

  for (const k of keys) {
    value = value[k];
    if (value === undefined) {
      console.warn(`Translation missing for ${language}.${key}`);
      return key;
    }
  }

  return value;
}
