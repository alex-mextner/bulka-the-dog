import { writeFile } from 'node:fs/promises';
import schema from '../client/cms/section-schema.json' with { type: 'json' };
import { blockNames } from '../client/cms/seed.ts';

// Developer-only generation. Static object literals let Conloca read the full
// field vocabulary without executing site code. This never edits CMS pages.
const humanize = key => key.replace(/^ui\./, '').replaceAll('.', ' · ').replaceAll('_', ' ');
const text = label => ({ type: 'text', label });
const paragraph = label => ({ type: 'textarea', label });
const photoFields = {
  src: text('Full-size image URL'), thumbSrc: text('Thumbnail URL (optional)'),
  alt: text('Alternative text'), caption: paragraph('Caption'),
};
const photo = label => ({ type: 'object', label, objectFields: photoFields });
const copy = keys => ({
  type: 'object', label: 'Text',
  objectFields: Object.fromEntries(keys.map(key => [key.replaceAll('.', '__'), paragraph(humanize(key))])),
});
function fieldsFor(name) {
  const definition = schema[name];
  const fields = { copy: copy(definition.copyKeys) };
  if (Object.keys(definition.photos).length) fields.photos = {
    type: 'object', label: 'Photos',
    objectFields: Object.fromEntries(Object.keys(definition.photos).map(key => [key, photo(humanize(key))])),
  };
  if (name === 'Habits') fields.items = {
    type: 'array', label: 'Habits',
    defaultItemProps: { id: '', emoji: '🐾', title: '', body: '', showPhotos: false },
    arrayFields: {
      id: text('Stable key'), emoji: text('Symbol'), title: text('Heading'), body: paragraph('Story'),
      showPhotos: { type: 'radio', label: 'Show sticky photos', options: [{ label: 'Yes', value: true }, { label: 'No', value: false }] },
      photo: photo('First photo'), secondaryPhoto: photo('Second photo'),
    },
  };
  if (name === 'Skills') fields.commands = {
    type: 'array', label: 'Commands', arrayFields: { label: text('Command') }, defaultItemProps: { label: '' },
  };
  if (name === 'Health') fields.healthItems = {
    type: 'array', label: 'Health notes',
    arrayFields: {
      body: paragraph('Note'),
      icon: { type: 'select', label: 'Icon', options: ['Crosshair', 'Bone', 'Worm', 'Ban', 'Heart'].map(value => ({ label: value, value })) },
    },
    defaultItemProps: { body: '', icon: 'Heart' },
  };
  if (name === 'Questions') fields.items = {
    type: 'array', label: 'Questions & answers',
    arrayFields: { id: text('Stable key'), question: text('Question'), answer: paragraph('Answer') },
    defaultItemProps: { id: '', question: '', answer: '' },
  };
  if (name === 'PhotoGallery') fields.photosList = {
    type: 'array', label: 'Gallery photos', arrayFields: photoFields,
    defaultItemProps: { src: '/placeholder.svg', alt: '', caption: '' },
  };
  if (name === 'Contact') fields.mapUrl = text('Map destination URL');
  return fields;
}

// Inserted blocks inherit translated fallback copy from the page's language.
// Keep repeaters explicitly empty so a new block does not copy authored seed
// stories or silently persist Russian text in an English/Serbian document.
function emptyDefaults(name) {
  const props = { copy: {} };
  if (name === 'Habits' || name === 'Questions') props.items = [];
  if (name === 'Skills') props.commands = [];
  if (name === 'Health') props.healthItems = [];
  if (name === 'PhotoGallery') props.photosList = [];
  return props;
}

let output = `// Generated by scripts/generate-puck-definitions.mjs. Do not hand-edit.\n// Literal fields/defaults are intentional: Conloca reads them without executing code.\nimport type { Field } from '@puckeditor/core';\nimport type { PageRootProps, SectionContentData } from '../client/cms/types';\ntype SectionDefinition = { label: string; fields: Record<string, Field>; defaultProps: SectionContentData };\n`;
output += `\nexport const RootDefinition: { fields: { locale: Field; socialImage: Field; copy: Field }; defaultProps: PageRootProps } = ${JSON.stringify({
  fields: {
    locale: { type: 'select', label: 'Page language', options: [
      { label: 'Русский', value: 'ru' }, { label: 'Srpski', value: 'rs' }, { label: 'English', value: 'en' },
    ] },
    socialImage: text('Social preview image URL'), copy: copy(schema.root.copyKeys),
  },
  defaultProps: { locale: 'ru', title: 'Bulka', description: '', socialImage: '/og-image.jpg', copy: {} },
}, null, 2)};\n`;
for (const name of blockNames) {
  output += `\nexport const ${name}Definition: SectionDefinition = ${JSON.stringify({
    label: schema[name].label, fields: fieldsFor(name), defaultProps: emptyDefaults(name),
  }, null, 2)};\n`;
}
await writeFile(new URL('../src/puck.definitions.ts', import.meta.url), output);
console.log('Generated nine core and one optional Game definition; saved CMS content was not changed.');
